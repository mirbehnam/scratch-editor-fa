const persianDigits = '۰۱۲۳۴۵۶۷۸۹';
const translateDigits = value => value.replace(/\d/g, digit => persianDigits[Number(digit)]);

const transliterate = value => {
    const digraphs = {
        sh: 'ش',
        ch: 'چ',
        kh: 'خ',
        gh: 'غ',
        zh: 'ژ',
        ph: 'ف',
        th: 'ت',
        oo: 'و',
        ee: 'ی',
        ou: 'او',
        ow: 'او',
        ai: 'ای',
        ay: 'ای',
        ea: 'ی'
    };
    const letters = {
        a: 'ا',
        b: 'ب',
        c: 'ک',
        d: 'د',
        e: 'ِ',
        f: 'ف',
        g: 'گ',
        h: 'ه',
        i: 'ی',
        j: 'ج',
        k: 'ک',
        l: 'ل',
        m: 'م',
        n: 'ن',
        o: 'و',
        p: 'پ',
        q: 'ک',
        r: 'ر',
        s: 'س',
        t: 'ت',
        u: 'و',
        v: 'و',
        w: 'و',
        x: 'کس',
        y: 'ی',
        z: 'ز'
    };
    let result = value.toLowerCase();
    Object.entries(digraphs).forEach(([latin, persian]) => {
        result = result.replaceAll(latin, persian);
    });
    return translateDigits(Array.from(result).map(character => letters[character] || character)
        .join(''));
};

const translateToken = (token, library) => {
    if (/^\d+$/.test(token)) return translateDigits(token);
    if (library === 'sounds' && noteNames[token]) return `نت ${noteNames[token]}`;
    if (letterNames[token]) return letterNames[token];
    return words[token.toLowerCase()] || transliterate(token);
};

const translateWords = (name, library) => name
    .replace(/(?<=[A-Za-z])(?=\d)|(?<=\d)(?=[A-Za-z])/g, ' ')
    .split(/[\s-]+/)
    .filter(Boolean)
    .map(token => translateToken(token, library))
    .join(' ');

