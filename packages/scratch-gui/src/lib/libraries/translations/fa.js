const translateSoundNote = name => {
    const match = name.match(/^([A-G])(2)? (.+)$/);
    if (!match || !instrumentNames[match[3]]) return null;
    const octave = match[2] ? ' ۲' : '';
    return `${instrumentNames[match[3]]}، نت ${noteNames[match[1]]}${octave}`;
};

const translatePersianLibraryName = (library, name) => {
    const trimmedName = name.trim();
    const exactName = exactNames[library] && exactNames[library][trimmedName];
    if (exactName) return exactName;

    if (library === 'sounds') {
        const noteName = translateSoundNote(trimmedName);
        if (noteName) return noteName;
    }

    const letterPattern = trimmedName.match(/^(Block|Glow|Story)-([A-Z])$/);
    if (letterPattern) {
        const prefixes = {Block: 'بلوک', Glow: 'حرف درخشان', Story: 'حرف داستانی'};
        return `${prefixes[letterPattern[1]]} ${letterNames[letterPattern[2]]}`;
    }

    return translateWords(trimmedName, library);
};

